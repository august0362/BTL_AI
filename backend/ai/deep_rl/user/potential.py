def _is_endgame(board: chess.Board) -> bool:
    """Dùng quy tắc chọn bảng vua của Benchmark 2."""
    if not board.queens:
        return True
    return all(
        (board.occupied_co[color] & ~board.pawns & ~board.kings).bit_count() <= 1
        for color in (chess.WHITE, chess.BLACK)
    )


def evaluate_cp(board: chess.Board) -> int:
    """Tính vật chất và bảng ô Michniewski theo góc nhìn bên tới lượt."""
    endgame = _is_endgame(board)
    white_score = 0
    for square, piece in board.piece_map().items():
        table = (
            KING_ENDGAME_TABLE
            if endgame and piece.piece_type == chess.KING
            else PST_TABLES[piece.piece_type]
        )
        index = chess.square_mirror(square) if piece.color == chess.WHITE else square
        value = PIECE_VALUES[piece.piece_type] + table[index]
        white_score += value if piece.color == chess.WHITE else -value
    return white_score if board.turn == chess.WHITE else -white_score


def potential(board: chess.Board, scale: float) -> float:
    """Đưa điểm bên tới lượt về thang tiềm năng đã cấu hình."""
    if scale == 0:
        return 0.0
    return scale * math.tanh(evaluate_cp(board) / 400.0)
